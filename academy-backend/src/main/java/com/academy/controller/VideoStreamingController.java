package com.academy.controller;

import com.academy.dto.response.ApiResponse;
import com.academy.exception.BadRequestException;
import com.academy.exception.ForbiddenException;
import com.academy.repository.VideoAssetRepository;
import com.academy.security.UserPrincipal;
import com.academy.service.LessonService;
import com.academy.service.VideoStorageService;
import com.academy.service.VideoTokenService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.servlet.http.HttpServletRequest;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.core.io.InputStreamResource;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.util.UUID;

@Slf4j
@RestController
@RequestMapping("/api/v1/videos")
@RequiredArgsConstructor
@Tag(name = "Video Streaming", description = "Self-hosted video upload and HTTP Range streaming")
public class VideoStreamingController {

    private final VideoStorageService  videoStorageService;
    private final VideoTokenService    videoTokenService;
    private final LessonService        lessonService;
    private final VideoAssetRepository videoAssetRepository;

    /** Default chunk size served per Range request: 10 MB. */
    private static final long DEFAULT_CHUNK = 10L * 1024 * 1024;

    // ─────────────────────────────────────────────────────────────────────────
    // Upload
    // ─────────────────────────────────────────────────────────────────────────

    /**
     * Upload (or replace) the video file for a lesson.
     * <p>
     * The file is streamed directly to disk via {@link VideoStorageService};
     * no DB transaction is held open during the file copy.  The subsequent
     * metadata write is handled atomically inside
     * {@link LessonService#registerLocalVideo}.
     */
    @PostMapping(value = "/{lessonId}/upload", consumes = MediaType.MULTIPART_FORM_DATA_VALUE)
    @PreAuthorize("hasAnyRole('INSTRUCTOR', 'ADMIN')")
    @Operation(summary = "Upload a video file for a lesson (multipart, up to 4 GB)")
    public ResponseEntity<ApiResponse<Void>> uploadVideo(
            @PathVariable UUID lessonId,
            @RequestParam("video") MultipartFile videoFile,
            @AuthenticationPrincipal UserPrincipal principal) throws IOException {

        // Validate file
        if (videoFile == null || videoFile.isEmpty()) {
            throw new BadRequestException("Video file is required");
        }
        String contentType = videoFile.getContentType();
        if (contentType == null || !contentType.startsWith("video/")) {
            throw new BadRequestException("Only video files are accepted (video/*)");
        }

        // Ownership check — runs in its own read-only transaction inside the service
        lessonService.verifyInstructorCanModifyLesson(lessonId, principal.getId(), principal.getRole());

        // Stream the file to disk (long operation — no DB connection held)
        String filePath = videoStorageService.storeVideo(
                videoFile.getInputStream(),
                videoFile.getOriginalFilename(),
                videoFile.getSize()
        );

        // Persist metadata atomically (own @Transactional in LessonServiceImpl)
        lessonService.registerLocalVideo(
                lessonId,
                filePath,
                videoFile.getOriginalFilename(),
                contentType,
                videoFile.getSize()
        );

        log.info("Video uploaded for lesson {}: {}", lessonId, filePath);
        return ResponseEntity.ok(ApiResponse.success("Video uploaded successfully"));
    }

    // ─────────────────────────────────────────────────────────────────────────
    // Stream  (HTTP Range)
    // ─────────────────────────────────────────────────────────────────────────

    /**
     * Stream a lesson video using HTTP Range requests.
     * <p>
     * Access is controlled by a short-lived signed token (not by Spring Security),
     * so this endpoint is declared {@code permitAll} in SecurityConfig.
     * The token is generated by {@link LessonService#getVideoUrl}.
     * On every request, the server verifies the token, resolves the associated
     * user, and revalidates live course authorization.
     */
    @GetMapping("/{lessonId}/stream")
    @Operation(summary = "Stream a video with HTTP 206 Partial Content support")
    public ResponseEntity<InputStreamResource> streamVideo(
            @PathVariable UUID lessonId,
            @RequestParam(required = false) String token,
            HttpServletRequest request) throws IOException {

        // ── 1. Token & Live User Authorization ────────────────────────────────
        var validatedOpt = videoTokenService.validateAndResolve(token, lessonId);
        if (validatedOpt.isEmpty()) {
            return ResponseEntity.status(HttpStatus.FORBIDDEN).build();
        }

        UUID userId = validatedOpt.get().userId();
        if (userId == null || !lessonService.canUserStreamLesson(lessonId, userId)) {
            return ResponseEntity.status(HttpStatus.FORBIDDEN).build();
        }

        // Supplementary browser navigation guard: reject direct top-level document
        // navigation (e.g. pasting the stream URL into a new browser tab).
        String secFetchDest = request.getHeader("Sec-Fetch-Dest");
        if ("document".equalsIgnoreCase(secFetchDest)) {
            return ResponseEntity.status(HttpStatus.FORBIDDEN).build();
        }

        // ── 2. Resolve Video File Path & Content-Type ─────────────────────────
        String filePath    = null;
        String contentType = "video/mp4";

        var assetOpt = videoAssetRepository.findByLessonId(lessonId);
        if (assetOpt.isPresent()) {
            var asset = assetOpt.get();
            filePath = asset.getFilePath();
            if (asset.getContentType() != null && !asset.getContentType().isBlank()) {
                contentType = asset.getContentType();
            }
        } else {
            var lesson = lessonService.findById(lessonId);
            if (lesson.getVideoFilePath() != null && !lesson.getVideoFilePath().isBlank()) {
                filePath = lesson.getVideoFilePath();
            } else if (lesson.isLocalVideo()) {
                filePath = lesson.getMuxPlaybackId().substring("local:".length());
            }
        }

        if (filePath == null || filePath.isBlank()) {
            throw new BadRequestException("No video found for this lesson");
        }

        if (!videoStorageService.videoExists(filePath)) {
            return ResponseEntity.status(HttpStatus.NOT_FOUND).build();
        }

        long totalSize = videoStorageService.getVideoSize(filePath);
        if (totalSize <= 0) {
            return ResponseEntity.status(HttpStatus.NOT_FOUND).build();
        }

        // ── 3. Require & Parse HTTP Range Header ──────────────────────────────
        // Reject full-file download attempts that omit a valid byte-range header.
        // HTML5 <video> elements across Chrome, Firefox, Edge, and Safari/iOS
        // always use byte-range requests.
        String rangeHeader = request.getHeader(HttpHeaders.RANGE);
        if (rangeHeader == null || !rangeHeader.startsWith("bytes=")) {
            return ResponseEntity.status(HttpStatus.FORBIDDEN).build();
        }

        String rangeSpec = rangeHeader.substring(6).trim();
        // Reject empty or multi-part ranges (e.g. "bytes=0-50, 100-150")
        if (rangeSpec.isEmpty() || rangeSpec.contains(",")) {
            return ResponseEntity.status(HttpStatus.REQUESTED_RANGE_NOT_SATISFIABLE)
                    .header(HttpHeaders.CONTENT_RANGE, "bytes */" + totalSize)
                    .build();
        }

        long rangeStart = -1;
        long rangeEnd   = -1;

        try {
            String[] parts = rangeSpec.split("-", -1);
            if (parts.length != 2) {
                rangeStart = -1;
            } else if (parts[0].isBlank()) {
                // Suffix range "bytes=-N": the last N bytes (used by Safari/iOS).
                if (!parts[1].isBlank()) {
                    long suffixLen = Long.parseLong(parts[1].trim());
                    if (suffixLen > 0) {
                        long cappedSuffix = Math.min(suffixLen, Math.min(totalSize, DEFAULT_CHUNK));
                        rangeStart = totalSize - cappedSuffix;
                        rangeEnd   = totalSize - 1;
                    }
                }
            } else {
                rangeStart = Long.parseLong(parts[0].trim());
                long maxAllowedEnd = (rangeStart >= 0 && rangeStart < totalSize)
                        ? Math.min(totalSize - 1, rangeStart + DEFAULT_CHUNK - 1)
                        : -1;
                if (!parts[1].isBlank()) {
                    long requestedEnd = Long.parseLong(parts[1].trim());
                    if (requestedEnd < rangeStart) {
                        rangeStart = -1; // invalid range: end < start
                    } else {
                        rangeEnd = Math.min(requestedEnd, maxAllowedEnd);
                    }
                } else {
                    rangeEnd = maxAllowedEnd;
                }
            }
        } catch (NumberFormatException e) {
            rangeStart = -1;
        }

        if (rangeStart < 0 || rangeStart >= totalSize || rangeEnd < rangeStart || rangeEnd >= totalSize) {
            return ResponseEntity.status(HttpStatus.REQUESTED_RANGE_NOT_SATISFIABLE)
                    .header(HttpHeaders.CONTENT_RANGE, "bytes */" + totalSize)
                    .build();
        }

        long contentLength = rangeEnd - rangeStart + 1;

        // ── 4. Build 206 Partial Content Response ─────────────────────────────
        var stream = videoStorageService.streamVideo(filePath, rangeStart, rangeEnd);

        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.parseMediaType(contentType));
        headers.set(HttpHeaders.ACCEPT_RANGES, "bytes");
        headers.set(HttpHeaders.CONTENT_RANGE,
                "bytes " + rangeStart + "-" + rangeEnd + "/" + totalSize);
        headers.setContentLength(contentLength);
        headers.set(HttpHeaders.CACHE_CONTROL, "private, no-store, no-cache, must-revalidate");
        headers.set(HttpHeaders.CONTENT_DISPOSITION, "inline");
        headers.set("X-Content-Type-Options", "nosniff");

        return ResponseEntity.status(HttpStatus.PARTIAL_CONTENT)
                .headers(headers)
                .body(new InputStreamResource(stream));
    }
}
